#!/usr/bin/env bash
# Rebuild packages/zarrita/src/codecs/pcodec-wasm.ts from packages/zarrita/pcodec-wasm (Rust).
# Needs a Rust toolchain with the wasm32-unknown-unknown target:
#   rustup target add wasm32-unknown-unknown
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CRATE="$ROOT/packages/zarrita/pcodec-wasm"
OUT="$ROOT/packages/zarrita/src/codecs/pcodec-wasm.ts"
TARGET_DIR="${CARGO_TARGET_DIR:-$CRATE/target}"

# run from the crate so its .cargo/config.toml (SIMD) applies
(cd "$CRATE" && cargo build --release --target wasm32-unknown-unknown --target-dir "$TARGET_DIR")
WASM="$TARGET_DIR/wasm32-unknown-unknown/release/zarrita_pcodec_wasm.wasm"
PCO_VERSION="$(sed -n 's/^pco = "=\(.*\)"/\1/p' "$CRATE/Cargo.toml")"
SHA="$(shasum -a 256 "$WASM" | cut -d' ' -f1)"
BYTES="$(wc -c < "$WASM" | tr -d ' ')"

{
	echo "// Generated by scripts/build-pcodec-wasm.sh from packages/zarrita/pcodec-wasm: do not edit."
	echo "// pco ${PCO_VERSION}; ${BYTES} bytes of WebAssembly; sha256 ${SHA}"
	printf 'export const wasmBase64 =\n\t"'
	base64 < "$WASM" | tr -d '\n'
	printf '";\n'
} > "$OUT"
echo "wrote $OUT (${BYTES} bytes of wasm, sha256 ${SHA})"
